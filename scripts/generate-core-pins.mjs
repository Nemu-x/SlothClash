/**
 * Computes the SHA-256 pin set for the embedded mihomo core(s) and writes it
 * as an NSIS include (`core_pins.nsh`, `!define SLOTH_CORE_SHA256_PINS`).
 *
 * WHY: the privileged service only spawns a core whose bytes match a pinned
 * hash recorded in its environment. After a core bump the hash changes, but an
 * already-installed service keeps the old pin → `does not match any pinned
 * hash` on connect. The Windows installer re-pins the service on upgrade using
 * this define, so a core bump does not strand users on a stale pin. (macOS /
 * Linux rely on the in-app reinstall banner — see core_pin_mismatch.go.)
 *
 * This MUST mirror Go's pinnedCoreHashesFromEmbed(): same glob
 * (build/sidecar/sloth-mihomo*, excluding pre-fork verge leftovers), same
 * SHA-256, so the installer-written pin equals what the client embeds.
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

function findRepoRoot() {
  let d = process.cwd()
  for (let i = 0; i < 8; i++) {
    if (
      fs.existsSync(path.join(d, 'apps', 'sloth-clash-desktop', 'wails.json'))
    )
      return d
    const p = path.dirname(d)
    if (p === d) break
    d = p
  }
  return path.resolve(__dirname, '..')
}

export function generateCorePins() {
  const repoRoot = findRepoRoot()
  const appDir = path.join(repoRoot, 'apps', 'sloth-clash-desktop')
  const sidecarDir = path.join(appDir, 'build', 'sidecar')
  const destNsh = path.join(
    appDir,
    'build',
    'windows',
    'installer',
    'core_pins.nsh',
  )

  let hashes = []
  if (fs.existsSync(sidecarDir)) {
    const files = fs
      .readdirSync(sidecarDir)
      .filter((f) => f.startsWith('sloth-mihomo'))
      .filter((f) => !f.toLowerCase().includes('verge'))
      // Windows installer pins the Windows core(s) it will embed.
      .filter((f) => f.includes('windows') || f.endsWith('.exe'))
      .sort()
    hashes = files.map((f) => {
      const buf = fs.readFileSync(path.join(sidecarDir, f))
      return crypto.createHash('sha256').update(buf).digest('hex')
    })
  }

  const pins = [...new Set(hashes)].join(',')
  fs.mkdirSync(path.dirname(destNsh), { recursive: true })
  // Empty pins → the installer's re-pin block no-ops (guarded on non-empty).
  const body = `; Generated by scripts/generate-core-pins.mjs — do not edit.\n!define SLOTH_CORE_SHA256_PINS "${pins}"\n`
  fs.writeFileSync(destNsh, body, 'utf8')
  console.log(
    '[generate-core-pins] wrote',
    path.relative(repoRoot, destNsh),
    pins
      ? `(${hashes.length} core hash(es))`
      : '(no sidecar cores found — empty pin set)',
  )
  return pins
}

// Allow standalone run for verification (path-format-robust on Windows).
const invoked = process.argv[1]
  ? path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
  : false
if (invoked) {
  generateCorePins()
}
